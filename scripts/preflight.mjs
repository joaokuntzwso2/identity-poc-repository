import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const scenarios = JSON.parse(await readFile(resolve('config/scenario-catalog.json'), 'utf8'));
const clients = ['aurora-web', 'aurora-app', 'brisa-web', 'brisa-app'];
if (scenarios.length < 7) throw new Error('Missing mandatory demo scenarios');
if (new Set(scenarios.map(s => s.id)).size !== scenarios.length) throw new Error('Duplicate scenario identifiers');
const expected = ['M-02.1', 'M-02.2', 'M-02.3', 'M-02.4', 'M-02.5', 'M-02.6', 'M-02.7'];
for (const key of expected) if (!scenarios.find(s => s.id === key)) throw new Error(`Mandatory demo missing: ${key}`);
console.log('SCENARIO_CATALOG_VALID:', scenarios.length, 'scenarios', clients.length, 'independent clients required');
const known = ['PUBLIC_ORIGIN', 'OIDC_ISSUER', 'OIDC_AURORA_WEB_CLIENT_ID', 'OIDC_AURORA_APP_CLIENT_ID', 'OIDC_BRISA_WEB_CLIENT_ID', 'OIDC_BRISA_APP_CLIENT_ID'];
if (!process.env.OIDC_ISSUER) console.log('WSO2_RUNTIME: NOT_CONFIGURED; live acceptance is blocked until issuer and four clients are supplied');
for (const key of known) if (!process.env[key]) console.log(`OPTIONAL_AT_STATIC_CHECK: ${key} not set`);
console.log('STATIC_PREFLIGHT_COMPLETE (does not prove WSO2 acceptance).');
