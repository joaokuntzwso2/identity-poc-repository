#!/usr/bin/env bash
# BEGIN WSO2_LAB_AUTO_LOCAL_TLS (reviewable local-only trust helper)
if [[ "${1-}" == 'bootstrap' || "${1-}" == 'tenants-only' ]]; then
  _wso2_lab_repo="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
  if [[ -z "${NODE_EXTRA_CA_CERTS:-}" ]]; then
    _wso2_lab_ca="$(bash "$_wso2_lab_repo/scripts/wso2/bootstrap-local-tls.sh")" || exit 1
    export NODE_EXTRA_CA_CERTS="$_wso2_lab_ca"
  fi
fi
# END WSO2_LAB_AUTO_LOCAL_TLS
set -Eeuo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"
CMD="${1:-plan}"
case "$CMD" in
  # IAMCTL_BOOTSTRAP_V083 — pinned WSO2 IS 7.3-compatible v3.0.0
  iamctl-install) python3 scripts/wso2/iamctl-install.py install;;
  iamctl-init) python3 scripts/wso2/iamctl-install.py init;;
  iamctl)
    python3 scripts/wso2/iamctl-install.py install
    IAMCTL_BIN="$(python3 scripts/wso2/iamctl-install.py path)"
    exec "$IAMCTL_BIN" "${@:2}";;
  bootstrap)
    if [ "${WSO2_LAB_CONFIRM:-}" != 'CREATE_SYNTHETIC_RESOURCES' ];then
      echo 'LAB_ERROR: EXPLICIT_APPLY_ACK_REQUIRED' >&2; exit 2
    fi
    # Preserve successful carbon.super core resources, then bootstrap two
    # genuinely distinct tenant roots and their pairwise OIDC registrations.
    "$ROOT/wso2-lab.sh" core
    if [ -f var/wso2/lab.env ];then set -a; source var/wso2/lab.env; set +a;fi
    node scripts/wso2/tenant-brand-bootstrap.mjs bootstrap;;
  bootstrap-tenants)
    if [ "${WSO2_LAB_CONFIRM:-}" != 'CREATE_SYNTHETIC_RESOURCES' ];then
      echo 'LAB_ERROR: EXPLICIT_APPLY_ACK_REQUIRED' >&2; exit 2
    fi
    if [ -f var/wso2/lab.env ];then set -a; source var/wso2/lab.env; set +a;fi
    node scripts/wso2/tenant-brand-bootstrap.mjs bootstrap;;
  bootstrap-pairwise)
    # Do not silently create four customer clients in carbon.super.
    if [ "${WSO2_LAB_CONFIRM:-}" != 'CREATE_SYNTHETIC_RESOURCES' ];then
      echo 'LAB_ERROR: EXPLICIT_APPLY_ACK_REQUIRED' >&2; exit 2
    fi
    if [ -f var/wso2/lab.env ];then set -a; source var/wso2/lab.env; set +a;fi
    node scripts/wso2/tenant-brand-bootstrap.mjs bootstrap;;
  tenant-auth-check)
    if [ -f var/wso2/lab.env ];then set -a; source var/wso2/lab.env; set +a;fi
    node scripts/wso2/tenant-brand-bootstrap.mjs auth-check;;
  tenant-brand-status)
    if [ -f var/wso2/lab.env ];then set -a; source var/wso2/lab.env; set +a;fi
    node scripts/wso2/tenant-brand-bootstrap.mjs status;;
  reconcile-organizations|tenants-audit)
    if [ "${WSO2_LAB_CONFIRM:-}" != 'CREATE_SYNTHETIC_RESOURCES' ] && [ "$CMD" = reconcile-organizations ];then
      echo 'LAB_ERROR: EXPLICIT_APPLY_ACK_REQUIRED' >&2; exit 2
    fi
    if [ -f var/wso2/lab.env ];then set -a; source var/wso2/lab.env; set +a;fi
    if [ "$CMD" = reconcile-organizations ];then node scripts/wso2/reconcile-organizations.mjs
    else node scripts/wso2/tenants-audit.mjs;fi;;
  apply)
    echo 'LAB_ERROR: LEGACY_ROOT_PAIRWISE_APPLY_DISABLED_USE_bootstrap-pairwise' >&2
    exit 2;;
  plan|core|status|reset|bff-env)
    if [ "$CMD" = apply ] || [ "$CMD" = core ];then python3 scripts/wso2/iamctl-install.py init;fi
    if [ -f var/wso2/lab.env ];then
      # Config is operator-managed, chmod 600, no committed secrets.
      set -a; source var/wso2/lab.env; set +a
    fi
    if [ -f var/wso2/local-sector-tunnels.env ];then
      # Generated by disposable local tunnel utility; overrides old single sector base.
      set -a; source var/wso2/local-sector-tunnels.env; set +a
    fi
    node scripts/wso2/cli.mjs "$CMD";;
  operator)
    if [ -f var/wso2/lab.env ];then set -a; source var/wso2/lab.env; set +a;fi
    node scripts/wso2/operator-server.mjs;;
  sectors-local|bootstrap-local)
    if [ -f var/wso2/lab.env ];then set -a; source var/wso2/lab.env; set +a;fi
    if [ "$CMD" = bootstrap-local ];then python3 scripts/wso2/iamctl-install.py init; node scripts/wso2/local-sector-tunnels.mjs bootstrap
    else node scripts/wso2/local-sector-tunnels.mjs serve;fi;;
  sectors)
    if [ -f var/wso2/lab.env ];then set -a; source var/wso2/lab.env; set +a;fi
    node scripts/wso2/write-sectors.mjs;;
  test)node --test scripts/wso2/*.test.mjs;;
  docker-up)docker compose --env-file var/wso2/lab.env -f deploy/wso2/compose.yaml up -d;;
  docker-down)docker compose --env-file var/wso2/lab.env -f deploy/wso2/compose.yaml down;;
  *)echo 'Usage: ./wso2-lab.sh bootstrap|bootstrap-tenants|bootstrap-pairwise|tenant-auth-check|tenant-brand-status|core|plan|status|reset|bff-env|test|iamctl-*';exit 2;;
esac
